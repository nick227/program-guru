#!/usr/bin/env bash
# Isolated, user-level MySQL for local development. No sudo, no Docker, no system packages.
#
# Matches Railway's MySQL template (image `mysql:8`, which currently resolves to 8.4.13) and its
# start flags. Runs on 127.0.0.1:3307 with its own data directory, so it never touches a system
# MySQL or MariaDB on 3306.
#
#   scripts/local-mysql.sh setup      download (checksum-verified), initialize, create user + databases, write .env
#   scripts/local-mysql.sh start      start in the background (no-op if running)
#   scripts/local-mysql.sh stop       stop cleanly
#   scripts/local-mysql.sh status     show whether it is running and its version
#   scripts/local-mysql.sh autostart  install and enable a systemd user service (start on login)
#   scripts/local-mysql.sh shell      open a root client session
#   scripts/local-mysql.sh create-database NAME   an extra programs_app_* database for isolated runs (.env untouched)
set -euo pipefail

VERSION="8.4.13"
MD5="a9df9b2879009eb0bfdb9ece3315a3b1"   # from dev.mysql.com for the file below
TARBALL="mysql-${VERSION}-linux-glibc2.28-x86_64.tar.xz"
URL="https://dev.mysql.com/get/Downloads/MySQL-8.4/${TARBALL}"
PORT="${LOCAL_MYSQL_PORT:-3307}"

OPT="${HOME}/.local/opt"
BASEDIR="${OPT}/mysql-${VERSION}"
DOWNLOADS="${OPT}/downloads/mysql-${VERSION}"
STATE="${HOME}/.local/share/programs-app-mysql"
DATADIR="${STATE}/data"
RUNDIR="${STATE}/run"
SOCKET="${RUNDIR}/mysqld.sock"
PIDFILE="${RUNDIR}/mysqld.pid"
CNF="${STATE}/my.cnf"
ROOT_CNF="${STATE}/root.cnf"
COMPAT_LIB="${STATE}/lib"
UNIT="${HOME}/.config/systemd/user/programs-app-mysql.service"
REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

APP_USER="programs_app"
DATABASES=(programs_app_dev programs_app_shadow programs_app_test)

log() { printf '→ %s\n' "$*"; }
die() { printf '✖ %s\n' "$*" >&2; exit 1; }

export LD_LIBRARY_PATH="${COMPAT_LIB}${LD_LIBRARY_PATH:+:${LD_LIBRARY_PATH}}"

client() { "${BASEDIR}/bin/mysql" --defaults-extra-file="${ROOT_CNF}" "$@"; }
running() { [[ -S "${SOCKET}" ]] && "${BASEDIR}/bin/mysqladmin" --defaults-extra-file="${ROOT_CNF}" ping >/dev/null 2>&1; }

install_binaries() {
  if [[ -x "${BASEDIR}/bin/mysqld" ]]; then log "MySQL ${VERSION} already installed at ${BASEDIR}"; return; fi
  mkdir -p "${DOWNLOADS}"
  if [[ ! -f "${DOWNLOADS}/${TARBALL}" ]]; then
    log "Downloading ${TARBALL}"
    curl -fL --retry 3 -o "${DOWNLOADS}/${TARBALL}.part" "${URL}"
    mv "${DOWNLOADS}/${TARBALL}.part" "${DOWNLOADS}/${TARBALL}"
  fi
  local actual; actual="$(md5sum "${DOWNLOADS}/${TARBALL}" | cut -d' ' -f1)"
  [[ "${actual}" == "${MD5}" ]] || die "Checksum mismatch for ${TARBALL}: ${actual}"
  log "Checksum verified; extracting to ${BASEDIR}"
  mkdir -p "${BASEDIR}.part"
  tar -xJf "${DOWNLOADS}/${TARBALL}" -C "${BASEDIR}.part" --strip-components=1
  mv "${BASEDIR}.part" "${BASEDIR}"
}

compat_libs() {
  # Ubuntu 24.04 ships libaio as libaio.so.1t64; the MySQL tarball links against libaio.so.1.
  mkdir -p "${COMPAT_LIB}"
  if ! ldconfig -p | grep -q 'libaio.so.1 '; then
    local src; src="$(ldconfig -p | awk '/libaio\.so\.1t64 /{print $NF; exit}')"
    [[ -n "${src}" ]] || die "libaio not found. Install it once with: sudo apt install libaio1t64"
    ln -sf "${src}" "${COMPAT_LIB}/libaio.so.1"
  fi
}

write_config() {
  mkdir -p "${DATADIR}" "${RUNDIR}" "${STATE}/log"
  chmod 700 "${STATE}"
  cat > "${CNF}" <<EOF
# Generated by scripts/local-mysql.sh. Mirrors Railway's MySQL template start command:
#   mysqld --innodb-use-native-aio=0 --disable-log-bin --performance_schema=0
[mysqld]
basedir=${BASEDIR}
datadir=${DATADIR}
socket=${SOCKET}
pid-file=${PIDFILE}
port=${PORT}
bind-address=127.0.0.1
mysqlx=OFF
innodb_use_native_aio=0
disable-log-bin
performance_schema=0
log-error=${STATE}/log/error.log
EOF
}

initialize() {
  if [[ -d "${DATADIR}/mysql" ]]; then log "Data directory already initialized"; return; fi
  log "Initializing data directory"
  "${BASEDIR}/bin/mysqld" --defaults-file="${CNF}" --initialize-insecure
  local pw; pw="$(head -c 24 /dev/urandom | base64 | tr -dc 'A-Za-z0-9' | head -c 24)"
  start_server
  "${BASEDIR}/bin/mysql" --no-defaults -uroot --socket="${SOCKET}" \
    -e "ALTER USER 'root'@'localhost' IDENTIFIED BY '${pw}';"
  umask 077
  printf '[client]\nuser=root\npassword=%s\nsocket=%s\n' "${pw}" "${SOCKET}" > "${ROOT_CNF}"
}

create_app_user() {
  local env_file="${REPO}/.env" pw=""
  if [[ -f "${env_file}" ]] && grep -q "^DATABASE_URL=mysql://${APP_USER}:" "${env_file}"; then
    pw="$(sed -n "s#^DATABASE_URL=mysql://${APP_USER}:\([^@]*\)@.*#\1#p" "${env_file}")"
  fi
  [[ -n "${pw}" ]] || pw="$(head -c 24 /dev/urandom | base64 | tr -dc 'A-Za-z0-9' | head -c 24)"
  local sql="CREATE USER IF NOT EXISTS '${APP_USER}'@'localhost' IDENTIFIED BY '${pw}';
ALTER USER '${APP_USER}'@'localhost' IDENTIFIED BY '${pw}';
CREATE USER IF NOT EXISTS '${APP_USER}'@'127.0.0.1' IDENTIFIED BY '${pw}';
ALTER USER '${APP_USER}'@'127.0.0.1' IDENTIFIED BY '${pw}';"
  for db in "${DATABASES[@]}"; do
    sql+="
CREATE DATABASE IF NOT EXISTS \`${db}\`;
GRANT ALL PRIVILEGES ON \`${db}\`.* TO '${APP_USER}'@'localhost';
GRANT ALL PRIVILEGES ON \`${db}\`.* TO '${APP_USER}'@'127.0.0.1';"
  done
  client -e "${sql}"
  log "User ${APP_USER} has access to: ${DATABASES[*]}"

  local url="mysql://${APP_USER}:${pw}@127.0.0.1:${PORT}"
  if [[ ! -f "${env_file}" ]]; then
    cp "${REPO}/.env.example" "${env_file}"
    log "Created .env from .env.example"
  fi
  # Only the two local database URLs are rewritten; every other line of .env is left alone.
  sed -i "s#^DATABASE_URL=.*#DATABASE_URL=${url}/programs_app_dev#; s#^SHADOW_DATABASE_URL=.*#SHADOW_DATABASE_URL=${url}/programs_app_shadow#" "${env_file}"
  grep -q '^TEST_DATABASE_URL=' "${env_file}" \
    && sed -i "s#^TEST_DATABASE_URL=.*#TEST_DATABASE_URL=${url}/programs_app_test#" "${env_file}" \
    || printf 'TEST_DATABASE_URL=%s/programs_app_test\n' "${url}" >> "${env_file}"
  log ".env points at 127.0.0.1:${PORT}"
}

start_server() {
  if running; then log "Already running on 127.0.0.1:${PORT}"; return; fi
  if ss -ltn 2>/dev/null | grep -q "127.0.0.1:${PORT} "; then die "Port ${PORT} is in use by another process"; fi
  "${BASEDIR}/bin/mysqld" --defaults-file="${CNF}" --daemonize >/dev/null
  for _ in $(seq 1 60); do
    [[ -S "${SOCKET}" ]] && "${BASEDIR}/bin/mysqladmin" --no-defaults --socket="${SOCKET}" -uroot ping >/dev/null 2>&1 && break
    [[ -f "${ROOT_CNF}" ]] && running && break
    sleep 0.5
  done
  log "Started on 127.0.0.1:${PORT}"
}

stop_server() {
  if ! running; then log "Not running"; return; fi
  "${BASEDIR}/bin/mysqladmin" --defaults-extra-file="${ROOT_CNF}" shutdown
  log "Stopped"
}

status() {
  if running; then
    printf 'running  127.0.0.1:%s  %s\n' "${PORT}" "$(client -N -e 'SELECT VERSION()')"
  else
    printf 'stopped\n'
    return 1
  fi
}

autostart() {
  mkdir -p "$(dirname "${UNIT}")"
  cat > "${UNIT}" <<EOF
[Unit]
Description=Programs App local MySQL ${VERSION} (127.0.0.1:${PORT})

[Service]
Type=simple
Environment=LD_LIBRARY_PATH=${COMPAT_LIB}
ExecStart=${BASEDIR}/bin/mysqld --defaults-file=${CNF}
ExecStop=${BASEDIR}/bin/mysqladmin --defaults-extra-file=${ROOT_CNF} shutdown
Restart=on-failure
TimeoutStopSec=60

[Install]
WantedBy=default.target
EOF
  stop_server
  systemctl --user daemon-reload
  systemctl --user enable --now programs-app-mysql.service
  log "Enabled systemd user service programs-app-mysql (starts with your WSL session)"
}

case "${1:-}" in
  setup)     install_binaries; compat_libs; write_config; initialize; start_server; create_app_user; status ;;
  start)     start_server ;;
  stop)      stop_server ;;
  status)    status ;;
  autostart) autostart ;;
  shell)     client ;;
  create-database)
    name="${2:-}"
    [[ "${name}" =~ ^programs_app_[a-z0-9_]+$ ]] || die "Name must look like programs_app_<suffix>"
    client -e "CREATE DATABASE IF NOT EXISTS \`${name}\`; GRANT ALL PRIVILEGES ON \`${name}\`.* TO '${APP_USER}'@'localhost'; GRANT ALL PRIVILEGES ON \`${name}\`.* TO '${APP_USER}'@'127.0.0.1';"
    log "Database ${name} ready for ${APP_USER}" ;;
  *) sed -n '2,14p' "$0"; exit 1 ;;
esac
