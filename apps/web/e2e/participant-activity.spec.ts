import { test, expect } from '@playwright/test'
import { setup } from './participant-activity-fixture'
import { itemId, groupId } from './fixtures'

test('simple completion and undo preserve a single valid action and omit empty sections', async ({ page }) => {
  const state = await setup(page, { simple: true })
  await expect(page.getByRole('heading', { name: "Today's Activity" })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'My Metrics' })).toHaveCount(0)
  await expect(page.getByRole('heading', { name: 'Together' })).toHaveCount(0)
  await expect(page.getByRole('button', { name: /^Start|Resume|Undo/ })).toHaveCount(0)
  await page.getByRole('button', { name: 'Complete', exact: true }).click()
  await expect(page).toHaveURL(/completed=/)
  await page.goto(`/occurrences/${itemId}`)
  await expect(page.getByRole('status').filter({ hasText: 'Completed' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Complete', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Undo completion' }).click()
  await expect(page.getByRole('button', { name: 'Complete', exact: true })).toBeVisible()
  expect(state.o.session?.status).toBe('FINISHED') // Undo preserves the old session.
  await expect(page.getByText('Active time')).toHaveCount(0)
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: test.info().outputPath('simple-activity.png'), fullPage: true })
})

test('timed activity starts, pauses, resumes and saves only entered metrics on completion', async ({ page }) => {
  const { calls } = await setup(page, { timed: true })
  await page.getByRole('button', { name: 'Start', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Pause', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Pause', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Resume', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Start', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Resume', exact: true }).click()
  await page.getByRole('button', { name: 'Complete', exact: true }).click()
  await expect(page).toHaveURL(/completed=/)
  expect(calls.filter(c => c.path.endsWith('/actions')).map(c => c.body.action)).toEqual(['START', 'PAUSE', 'RESUME', 'FINISH'])
  expect(calls.filter(c => c.path.endsWith('/results') && c.method === 'POST')).toHaveLength(0)
})

test('social gallery filters, attribution, sharing, revoke and reactions use actual group identity', async ({ page }) => {
  const { calls } = await setup(page, { social: true })
  const together = page.getByRole('region', { name: 'Together', exact: true })
  await expect(together.getByText('Carol Chen', { exact: true })).toBeVisible()
  await expect(together.getByRole('link', { name: 'Open Group' })).toHaveAttribute('href', new RegExp(groupId))
  const react = together.getByRole('button', { name: 'React 🔥 to Carol Chen' })
  await react.click()
  await expect(react).toHaveAttribute('aria-pressed', 'true')
  await react.click()
  await expect(react).toHaveAttribute('aria-pressed', 'false')
  const filters = page.getByRole('group', { name: 'Filter related media' })
  await filters.getByRole('button', { name: 'Mine', exact: true }).click()
  await expect(page.getByRole('button', { name: 'My recording', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Group recording', exact: true })).toHaveCount(0)
  await page.getByLabel('Media options', { exact: true }).click()
  await page.getByRole('button', { name: 'Share with group' }).click()
  await expect(page.getByRole('button', { name: 'Stop sharing with group' })).toBeVisible()
  expect(calls.find(c => c.path === '/media-publications')?.body).toMatchObject({ mediaId: 'mine', groupId, occurrenceKey: 'shared-occurrence-across-versions' })
  await page.getByRole('button', { name: 'Stop sharing with group' }).click()
  await expect(page.getByRole('button', { name: 'Share with group' })).toBeVisible()
  await page.getByLabel('Public sharing licence').selectOption('All rights reserved')
  await page.getByRole('button', { name: 'Share publicly', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Stop sharing publicly' })).toBeVisible()
  expect(calls.find(c => c.path === '/media-publications' && c.body?.audience === 'PUBLIC')?.body.license).toBe('All rights reserved')
  await page.getByRole('button', { name: 'Stop sharing publicly' }).click()
  await expect(page.getByRole('button', { name: 'Share publicly', exact: true })).toBeVisible()
  await filters.getByRole('button', { name: 'Public', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Public demonstration', exact: true })).toBeVisible()
  await expect(page.getByText('Taylor', { exact: true })).toBeVisible()
  await expect(page.getByLabel('Media options', { exact: true })).toHaveCount(0)
  await filters.getByRole('button', { name: 'All', exact: true }).click()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: test.info().outputPath('social-activity.png'), fullPage: true })
})

test('privacy keeps private group states unknown and locked public media unavailable', async ({ page }) => {
  const state = await setup(page, { social: true, privateOnly: true, locked: true })
  await expect(page.getByText('Nobody else has started yet. You could be first.')).toHaveCount(0)
  await expect(page.getByRole('button', { name: /^React/ })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Public demonstration', exact: true })).toHaveCount(0)
  state.deny()
  await page.getByRole('button', { name: 'My recording', exact: true }).click()
  await expect(page.getByRole('dialog').getByRole('alert')).toContainText('You cannot view this media')
  await expect(page.getByRole('dialog').locator('img')).toHaveCount(0)
})

test('direct upload stays visible while processing then attaches without a media picker', async ({ page }) => {
  const state = await setup(page)
  await page.locator('#related-media input[type=file]').setInputFiles({ name: 'photo.png', mimeType: 'image/png', buffer: Buffer.from('photo') })
  await expect(page.getByText('Processing…', { exact: true })).toBeVisible()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  state.ready()
  await expect(page.getByRole('button', { name: 'Uploaded photo', exact: true })).toBeVisible()
  expect(state.calls.find(c => c.path === '/media/uploads')?.body).toMatchObject({ target: { kind: 'RESULT_ENTRY', id: 'result-current' }, purpose: 'JOURNAL' })
  expect(state.calls.filter(c => c.path === '/media-publications')).toHaveLength(0)
})

