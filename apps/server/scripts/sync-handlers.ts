// Keeps src/handlers/index.ts and src/handlers/pending.ts in sync with the spec.
// Every operationId must have a handler export or fastify-openapi-glue refuses to start. Operations
// not implemented yet get a stub that answers 501 NOT_IMPLEMENTED, so gaps stay visible instead of silent.
import { load } from 'js-yaml'
import { readFileSync, readdirSync, writeFileSync } from 'fs'
import { resolve } from 'path'

const dir = resolve(__dirname, '../src/handlers')
const spec = load(readFileSync(resolve(__dirname, '../../../packages/api-spec/openapi.yaml'), 'utf8')) as any
const ops: string[] = []
for (const item of Object.values<any>(spec.paths)) for (const op of Object.values<any>(item)) if (op.operationId) ops.push(op.operationId)

const files = readdirSync(dir).filter((f) => f.endsWith('.ts') && !['index.ts', 'pending.ts'].includes(f)).sort()
const implemented = new Set<string>()
for (const f of files) {
  for (const m of readFileSync(resolve(dir, f), 'utf8').matchAll(/^export (?:async )?function (\w+)|^export const (\w+)/gm)) implemented.add((m[1] ?? m[2])!)
}
const unknown = [...implemented].filter((n) => !ops.includes(n))
const pending = ops.filter((o) => !implemented.has(o)).sort()

writeFileSync(
  resolve(dir, 'pending.ts'),
  `// GENERATED by scripts/sync-handlers.ts. Operations in the spec without a handler yet.\n` +
    (pending.length
      ? `import { notImplemented } from '../lib/errors'\n\n` + pending.map((o) => `export async function ${o}() {\n  throw notImplemented('${o}')\n}\n`).join('\n')
      : `// None: every operation is implemented.\nexport {}\n`),
)
writeFileSync(
  resolve(dir, 'index.ts'),
  `// GENERATED by scripts/sync-handlers.ts. Every operationId in the spec is exported from here.\n` +
    files.map((f) => `export * from './${f.replace(/\.ts$/, '')}'`).join('\n') +
    `\nexport * from './pending'\n`,
)
console.log(`✓ ${implemented.size - unknown.length}/${ops.length} operations implemented, ${pending.length} pending`)
if (unknown.length) console.log(`  Not in the spec (helpers must not be exported from handlers/): ${unknown.join(', ')}`)
